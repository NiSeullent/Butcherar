#!/bin/sh
# Collect "GZ_FORMAT(sym)" and "GZ_WRITER(sym)" marker lines from the given C files
# and write the probe/writer tables. Output is only replaced when it changes.
#   tools/gen_registry.sh build/gen/registry.c src/fmt/*.c src/codec/*.c
out="$1"; shift
tmp="$out.tmp"
fmts=$(grep -h '^GZ_FORMAT(' "$@" 2>/dev/null | sed 's/^GZ_FORMAT(\([A-Za-z0-9_]*\)).*/\1/' | LC_ALL=C sort -u)
wrs=$(grep -h '^GZ_WRITER(' "$@" 2>/dev/null | sed 's/^GZ_WRITER(\([A-Za-z0-9_]*\)).*/\1/' | LC_ALL=C sort -u)
{
    echo '/* generated by tools/gen_registry.sh - do not edit */'
    echo '#include "arc.h"'
    echo '#include "gz_write.h"'
    for f in $fmts; do echo "extern const gz_format $f;"; done
    for f in $wrs; do echo "extern const gz_writer $f;"; done
    echo 'const gz_format *const gz_formats[] = {'
    for f in $fmts; do echo "    &$f,"; done
    echo '    0'
    echo '};'
    echo 'const gz_writer *const gz_writers[] = {'
    for f in $wrs; do echo "    &$f,"; done
    echo '    0'
    echo '};'
} > "$tmp"
if cmp -s "$tmp" "$out" 2>/dev/null; then rm -f "$tmp"; else mv "$tmp" "$out"; fi
